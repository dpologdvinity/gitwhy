#!/bin/sh
# Write THIRD_PARTY_LICENSES: the license and notice files of every module linked into the
# gitwhy binary, plus the Go standard library. Release archives and packages ship this file,
# because the MIT, BSD and Apache licenses of our dependencies require their notices to travel
# with binary copies.
#
# Usage:    scripts/third-party-licenses.sh [output file]   (default: THIRD_PARTY_LICENSES)
# Needs:    go, with the module cache filled (go mod download).
# CI runs it and fails if the committed file differs (git diff --exit-code THIRD_PARTY_LICENSES).
set -eu

out=${1:-THIRD_PARTY_LICENSES}
cd "$(dirname "$0")/.."
tmp=$(mktemp)
trap 'rm -f "$tmp" "$tmp.mods"' EXIT

# The dependency set depends on the target OS (Windows pulls in different packages), so take the
# union over every OS we release for. Module versions are left out on purpose: a version bump
# that keeps the same license text should not change this file.
for goos in linux darwin windows; do
  GOOS=$goos go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}	{{.Dir}}{{end}}{{end}}' ./cmd/gitwhy
done | sort -u > "$tmp.mods"

{
  echo "Third-party licenses for gitwhy"
  echo "==============================="
  echo
  echo "The gitwhy binary includes the code below. Each part keeps its own license."
  echo "Generated by scripts/third-party-licenses.sh; do not edit by hand."

  # The Go runtime and standard library are linked into every Go binary.
  echo
  echo "--------------------------------------------------------------------------------"
  echo "Go standard library (https://go.dev)"
  echo "--------------------------------------------------------------------------------"
  echo
  cat "$(go env GOROOT)/LICENSE"

  # Tab-separated: module path, then its directory (a replace directive gives the local copy,
  # such as third_party/clipboard).
  while IFS='	' read -r path dir; do
    files=$(find "$dir" -maxdepth 1 -type f \( -iname 'LICENSE*' -o -iname 'LICENCE*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) | sort)
    if [ -z "$files" ]; then
      echo "third-party-licenses: no license file in $path ($dir)" >&2
      exit 1
    fi
    for f in $files; do
      echo
      echo "--------------------------------------------------------------------------------"
      echo "$path ($(basename "$f"))"
      echo "--------------------------------------------------------------------------------"
      echo
      cat "$f"
    done
  done < "$tmp.mods"
} > "$tmp"

chmod 644 "$tmp" # mktemp makes it 0600; archives keep file modes
mv "$tmp" "$out"
echo "wrote $out"
